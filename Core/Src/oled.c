/* =========================================================================
   SSD1306 / SH1106 OLED driver -- software bit-banged I2C (PB6=SCL, PB7=SDA)

   - STM32F1 hardware I2C has a well-known BUSY lockup bug, so we bit-bang.
   - Interrupts stay enabled: only the display task uses this bus and a task
     switch only stretches SCL low, which I2C slaves tolerate. This keeps the
     USART1 receive ISR responsive during a full screen refresh.
   - Framebuffer in RAM; OLED_Refresh() pushes one page (128 bytes) per tx.
   ========================================================================= */

